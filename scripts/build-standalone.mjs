import { build } from 'vite';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// Rebuild the single-file entry from the same Game/UI sources as the normal website.
const result = await build({
  configFile: false,
  logLevel: 'warn',
  base: './',
  build: {
    write: false,
    copyPublicDir: false,
    target: 'es2022',
    minify: true,
    cssCodeSplit: false,
    lib: { entry: resolve('src/standalone.ts'), name: 'PrismStandalone', formats: ['iife'] },
  },
});
const outputs = (Array.isArray(result) ? result : [result]).flatMap(r => r.output ?? []);
const entry = outputs.find(o => o.type === 'chunk' && o.isEntry);
const css = outputs.filter(o => o.type === 'asset' && o.fileName.endsWith('.css')).map(o => typeof o.source === 'string' ? o.source : Buffer.from(o.source).toString('utf8')).join('\n');
if (!entry || !css) throw new Error('Standalone build is missing JavaScript or CSS');
let html = await readFile('scripts/standalone-template.html', 'utf8');
if (!html.includes('<!-- STANDALONE_ASSETS -->')) throw new Error('Standalone template is missing its asset slot');
html = html.replace('<!-- STANDALONE_ASSETS -->', () =>
  `<!-- Generated by scripts/build-standalone.mjs; edit src/standalone.ts instead. -->\n<style>${css.replace(/<\/style/gi, '<\\/style')}</style>\n<script>${entry.code.replace(/<\/script/gi, '<\\/script')}</script>`);
await writeFile('index.html', html);
console.log(`Standalone rebuilt: ${Buffer.byteLength(html).toLocaleString()} bytes`);
